#include "HIDProfile.hpp"
#include <array>

bool HIDProfile::RemapReportIds(uint8_t firstId) {
    std::vector<HIDReportLayout> reports;
    if (!firstId || !ParseHIDDescriptor(descriptor.data(), descriptor.size(), reports)) return false;
    std::array<uint8_t, 256> ids{};
    for (size_t offset = 0; offset < descriptor.size();) {
        const uint8_t prefix = descriptor[offset++];
        if ((prefix & 0xfc) == 0x84) ids[descriptor[offset]] = 1;
        offset += (prefix & 3) == 3 ? 4 : prefix & 3;
    }
    unsigned next = firstId;
    for (auto& id : ids) if (id) {
        if (next > 255) return false;
        id = next++;
    }
    for (const auto& state : neutral) if (!ids[state.id]) return false;
    for (size_t offset = 0; offset < descriptor.size();) {
        const uint8_t prefix = descriptor[offset++];
        const size_t size = (prefix & 3) == 3 ? 4 : prefix & 3;
        if ((prefix & 0xfc) == 0x84) {
            descriptor[offset] = ids[descriptor[offset]];
            for (size_t i = 1; i < size; ++i) descriptor[offset + i] = 0;
        }
        offset += size;
    }
    for (auto& state : neutral) state.id = ids[state.id];
    return true;
}

